// ============================================================================
// Module: aes128  (Verilog-2001 conversion of aes128.sv)
// High-throughput pipelined AES-128 cipher. Structure, pipeline stages,
// enable shift register and handshake are identical to the original
// SystemVerilog version; only the SV-specific constructs were mapped to
// plain Verilog (see aes128Pkg.vh for the type mapping).
// ============================================================================
module aes128 (
  input  Clk_CI,
  input  Reset_RBI,
  input  Start_SI,
  input  NewCipherkey_SI,
  output Busy_SO,
  input  [127:0] Plaintext_DI,
  input  [127:0] Cipherkey_DI,
  output [127:0] Ciphertext_DO );

  `include "aes128Pkg.vh"

  // ------------------------------------------------------------------
  // Functions (identity in the flat 128-bit representation; kept so the
  // code mirrors the original module)
  // ------------------------------------------------------------------
  function [127:0] to_matrix;
    input [127:0] inp;
    begin
      to_matrix = inp;
    end
  endfunction

  function [127:0] to_logic;
    input [127:0] inp;
    begin
      to_logic = inp;
    end
  endfunction

  // ------------------------------------------------------------------
  // Signals
  // ------------------------------------------------------------------
  wire [127:0]  Plaintext_DN;
  reg  [127:0]  Plaintext_DP;
  wire [1279:0] CipherState_DN;          // 10 pipeline states, packed
  reg  [127:0]  CipherState_DP [0:9];    // 10 pipeline states
  wire [127:0]  Ciphertext_DN;
  reg  [127:0]  Ciphertext_DP;
  reg  [0:10]   EnCipherState_SN, EnCipherState_SP;

  wire [1407:0] Roundkeys_D;             // 11 round keys, packed
  wire [127:0]  LastSubMatrixOut_D;
  wire          KeyExpStart_S;
  wire          AllCipherStatesDisabled_S;
  wire          AllEnCipherStatesOred_S;

  genvar i;
  integer k;

  // ------------------------------------------------------------------
  // Component instantiations
  // ------------------------------------------------------------------
  keyExpansion keyExpansion_1 (
    .Clk_CI(Clk_CI),
    .Reset_RBI(Reset_RBI),
    .Start_SI(KeyExpStart_S),
    .Cipherkey_DI(Cipherkey_DI),
    .Roundkeys_DO(Roundkeys_D));

  // S-box of the last round.
  subMatrix lastSubMatrix (
    .In_DI(CipherState_DP[9]),
    .Out_DO(LastSubMatrixOut_D));

  // Perform full rounds (i.e., rounds one to nine).
  generate for (i=1; i<10; i=i+1) begin : gen_cipherRounds
    cipherRound cipherRounds (
      .StateIn_DI(CipherState_DP[i-1]),
      .Roundkey_DI(Roundkeys_D[128*i +: 128]),
      .StateOut_DO(CipherState_DN[128*i +: 128]));
  end endgenerate

  // ------------------------------------------------------------------
  // Next state logic
  // ------------------------------------------------------------------

  // Enable plaintext register only when start signal is set.
  assign Plaintext_DN = (Start_SI == 1'b1) ? Plaintext_DI : Plaintext_DP;

  // The enables for the cipher states are generated by a one-hot encoded
  // shift register, which gets the start signal as an input.
  always @* begin
    EnCipherState_SN = {1'b0, EnCipherState_SP[0:9]};
    if (Start_SI == 1'b1) begin
      EnCipherState_SN = {1'b1, EnCipherState_SP[0:9]};
    end else if (AllCipherStatesDisabled_S == 1'b1) begin
      EnCipherState_SN = EnCipherState_SP;
    end
  end

  // Perform last round (no MixColumns) and calculate the final state.
  assign Ciphertext_DN = (EnCipherState_SP[10] == 1'b1) ?
                           xor_matrix_logic(shift_rows(LastSubMatrixOut_D), Roundkeys_D[1407:1280]) :
                           Ciphertext_DP;

  // Perform initial "AddRoundKey".
  assign CipherState_DN[127:0] = to_matrix(Roundkeys_D[127:0] ^ Plaintext_DP);

  assign AllEnCipherStatesOred_S   = |EnCipherState_SP;
  assign AllCipherStatesDisabled_S = ~AllEnCipherStatesOred_S;

  // Key expansion only when both start and new-cipherkey are set.
  assign KeyExpStart_S = Start_SI & NewCipherkey_SI;

  // ------------------------------------------------------------------
  // Output assignment
  // ------------------------------------------------------------------
  assign Ciphertext_DO = to_logic(Ciphertext_DP);
  assign Busy_SO       = ~AllCipherStatesDisabled_S;

  // ------------------------------------------------------------------
  // Flip flops
  // ------------------------------------------------------------------
  always @(posedge Clk_CI or negedge Reset_RBI) begin
    if (~Reset_RBI) begin
      Plaintext_DP     <= 0;
      EnCipherState_SP <= 0;
      for (k=0; k<10; k=k+1) CipherState_DP[k] <= 0;
      Ciphertext_DP    <= 0;
    end else begin
      Plaintext_DP     <= Plaintext_DN;
      EnCipherState_SP <= EnCipherState_SN;

      if (EnCipherState_SP[0]  == 1'b1) CipherState_DP[0] <= CipherState_DN[127:0];
      if (EnCipherState_SP[1]  == 1'b1) CipherState_DP[1] <= CipherState_DN[255:128];
      if (EnCipherState_SP[2]  == 1'b1) CipherState_DP[2] <= CipherState_DN[383:256];
      if (EnCipherState_SP[3]  == 1'b1) CipherState_DP[3] <= CipherState_DN[511:384];
      if (EnCipherState_SP[4]  == 1'b1) CipherState_DP[4] <= CipherState_DN[639:512];
      if (EnCipherState_SP[5]  == 1'b1) CipherState_DP[5] <= CipherState_DN[767:640];
      if (EnCipherState_SP[6]  == 1'b1) CipherState_DP[6] <= CipherState_DN[895:768];
      if (EnCipherState_SP[7]  == 1'b1) CipherState_DP[7] <= CipherState_DN[1023:896];
      if (EnCipherState_SP[8]  == 1'b1) CipherState_DP[8] <= CipherState_DN[1151:1024];
      if (EnCipherState_SP[9]  == 1'b1) CipherState_DP[9] <= CipherState_DN[1279:1152];

      if (EnCipherState_SP[10] == 1'b1) Ciphertext_DP <= Ciphertext_DN;
    end
  end

endmodule
